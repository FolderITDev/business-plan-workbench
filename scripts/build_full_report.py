#!/usr/bin/env python3
"""Concatenate a case's numbered output files into a single-file report.

Deterministic helper. No LLM, no network. The folder bundle is the source of
truth; this just stitches `output/NN-*.md` into `output/00-full-report.md`
in numeric order. The generated report and any review notes are excluded.

Usage:
    python scripts/build_full_report.py cases/2026-06-23-ai-consulting-business
    python scripts/build_full_report.py <case> --out output/00-full-report.md
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

NUMBERED_RE = re.compile(r"^(\d{2})-.*\.md$")
DEFAULT_OUT_NAME = "00-full-report.md"
EXCLUDE_NAMES = {DEFAULT_OUT_NAME, "review-notes.md"}


def collect_sections(output_dir: Path) -> list[Path]:
    sections = []
    for p in sorted(output_dir.glob("*.md")):
        if p.name in EXCLUDE_NAMES:
            continue
        if NUMBERED_RE.match(p.name):
            sections.append(p)
    return sections


def build_report(output_dir: Path, out_path: Path) -> int:
    sections = collect_sections(output_dir)
    if not sections:
        print(f"No numbered NN-*.md files found in {output_dir}. Nothing to build.")
        return 1

    parts: list[str] = [
        "<!-- Generated by scripts/build_full_report.py. Do not edit by hand;",
        "     edit the numbered section files and rebuild. -->",
        "",
    ]
    for path in sections:
        body = path.read_text(encoding="utf-8").rstrip()
        parts.append(body)
        parts.append("")
        parts.append("---")
        parts.append("")

    # Drop the trailing separator.
    while parts and parts[-1] in ("", "---"):
        parts.pop()
    parts.append("")

    out_path.write_text("\n".join(parts), encoding="utf-8")
    rel = ", ".join(p.name for p in sections)
    print(f"Wrote {out_path} from {len(sections)} section(s): {rel}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a single-file report.")
    parser.add_argument("case_dir", help="Path to the case folder")
    parser.add_argument(
        "--out",
        default=None,
        help="Output path (default: <case>/output/00-full-report.md)",
    )
    args = parser.parse_args(argv)

    case_dir = Path(args.case_dir)
    output_dir = case_dir / "output"
    if not output_dir.is_dir():
        print(f"ERROR: no output/ folder in {case_dir}", file=sys.stderr)
        return 1

    out_path = Path(args.out) if args.out else output_dir / DEFAULT_OUT_NAME
    out_path.parent.mkdir(parents=True, exist_ok=True)
    return build_report(output_dir, out_path)


if __name__ == "__main__":
    raise SystemExit(main())
